const SATUAN_INDO = [
  '',
  'Satu',
  'Dua',
  'Tiga',
  'Empat',
  'Lima',
  'Enam',
  'Tujuh',
  'Delapan',
  'Sembilan',
  'Sepuluh',
  'Sebelas',
];

export function angkaKeKata(n: number): string {
  const num = Math.floor(Math.abs(n));
  if (num === 0) return 'Nol';
  if (num < 12) return SATUAN_INDO[num];
  if (num < 20) return `${angkaKeKata(num - 10)} Belas`;
  if (num < 100) {
    const puluh = Math.floor(num / 10);
    const sisa = num % 10;
    return `${angkaKeKata(puluh)} Puluh${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 200) {
    const sisa = num - 100;
    return `Seratus${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 1000) {
    const ratus = Math.floor(num / 100);
    const sisa = num % 100;
    return `${angkaKeKata(ratus)} Ratus${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 2000) {
    const sisa = num - 1000;
    return `Seribu${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 1_000_000) {
    const ribu = Math.floor(num / 1000);
    const sisa = num % 1000;
    return `${angkaKeKata(ribu)} Ribu${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 1_000_000_000) {
    const juta = Math.floor(num / 1_000_000);
    const sisa = num % 1_000_000;
    return `${angkaKeKata(juta)} Juta${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  if (num < 1_000_000_000_000) {
    const miliar = Math.floor(num / 1_000_000_000);
    const sisa = num % 1_000_000_000;
    return `${angkaKeKata(miliar)} Miliar${sisa > 0 ? ' ' + angkaKeKata(sisa) : ''}`;
  }
  return String(num);
}

export function terbilangRupiah(amount: number): string {
  if (!amount || amount <= 0) return 'Nol Rupiah';
  return `${angkaKeKata(amount)} Rupiah`;
}

